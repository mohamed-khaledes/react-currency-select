/**
 * Vendors an ISO 3166-1 alpha-2 -> ISO 4217 map into `src/countries.data.ts`,
 * so `country="DE"` can resolve to EUR and searching "DE" can find it.
 *
 * Source: `country-to-currency` (MIT) — a devDependency, never shipped.
 * Only countries whose currency exists in our dataset are kept, so a lookup
 * either returns a currency we can actually render or nothing at all.
 *
 * Run with `npm run gen:countries` after changing the currency dataset.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const raw = require("country-to-currency");
const map = raw.default ?? raw;

const dataset = readFileSync("src/currencies.ts", "utf8");
const known = new Set([...dataset.matchAll(/code: "([A-Z]{3})"/g)].map((m) => m[1]));

// Israel is deliberately absent from the dataset; PS -> ILS covers the shekel.
const EXCLUDED_COUNTRIES = new Set(["IL"]);

const rows = [];
const dropped = [];
for (const [country, code] of Object.entries(map).sort(([a], [b]) => a.localeCompare(b))) {
  if (!/^[A-Z]{2}$/.test(country) || EXCLUDED_COUNTRIES.has(country)) continue;
  if (!known.has(code)) {
    dropped.push(`${country}->${code}`);
    continue;
  }
  rows.push(`  ${country}: "${code}",`);
}

const file = `/**
 * GENERATED by scripts/gen-countries.mjs — do not edit by hand.
 *
 * ${rows.length} ISO 3166-1 alpha-2 country codes mapped to the ISO 4217 code
 * they use. Data from country-to-currency (MIT), a build-time devDependency.
 */
export const COUNTRY_CURRENCY: Record<string, string> = {
${rows.join("\n")}
};
`;

writeFileSync("src/countries.data.ts", file);
console.log(
  `wrote src/countries.data.ts — ${rows.length} countries, ${(Buffer.byteLength(file) / 1024).toFixed(1)} kB` +
    (dropped.length ? `\nskipped ${dropped.length} (currency not in dataset): ${dropped.join(", ")}` : ""),
);
